-- ── The decision function (alias + queue row + back-fill in one statement) ──

-- Mirrors confirm_upcoming_project_match(payload jsonb) (baseline:1512-1620).
-- Returns jsonb because the caller needs the back-filled worker ids for the
-- campaign-universe sync.
--
--   payload: { id, action: 'confirm' | 'override' | 'create' | 'reject' | 'reopen',
--              employer_id? | worksite_id?     (confirm / override: the target row;
--                                               confirm falls back to resolved_*),
--              create?: { employer_name, trading_name?, employer_category? }
--                     | { worksite_name, worksite_type, is_offshore? },
--              notes? }
--   returns: { review: <row>, alias_written: bool, backfilled_worker_ids: int[],
--              siblings_resolved: int }
CREATE OR REPLACE FUNCTION "public"."decide_name_match"("payload" "jsonb") RETURNS "jsonb"
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO 'public'
    AS $$
DECLARE
  v_id            bigint;
  v_action        text;
  v_notes         text;
  v_create        jsonb;
  v_target        integer;
  v_target_name   text;
  v_target_alt    text;
  v_other_name    text;
  v_status        text;
  v_method        text;
  v_n             integer := 0;
  v_row           public.name_match_reviews;
  v_alias_written boolean := false;
  v_backfilled    integer[] := '{}'::integer[];
  v_siblings      integer := 0;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'Only admins may decide name matches';
  END IF;

  v_id     := NULLIF(payload->>'id', '')::bigint;
  v_action := payload->>'action';
  v_notes  := payload->>'notes';
  v_create := CASE WHEN jsonb_typeof(payload->'create') = 'object' THEN payload->'create' ELSE NULL END;

  IF v_id IS NULL OR v_action IS NULL THEN
    RAISE EXCEPTION 'payload must include id and action';
  END IF;
  IF v_action NOT IN ('confirm', 'override', 'create', 'reject', 'reopen') THEN
    RAISE EXCEPTION 'unsupported action: %', v_action;
  END IF;

  SELECT * INTO v_row FROM public.name_match_reviews WHERE id = v_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'name_match_reviews row % not found', v_id;
  END IF;

  IF v_action IN ('confirm', 'override', 'create') THEN
    -- 1. Only an open (or auto) row can be decided; reopen a decided one first.
    IF v_row.status NOT IN ('needs_review', 'unmatched', 'auto') THEN
      RAISE EXCEPTION 'review % is already %; reopen it first', v_id, v_row.status;
    END IF;

    -- 2. The target row: created here (the only insert into employers /
    --    worksites on the import path) or named by the reviewer.
    IF v_action = 'create' THEN
      IF v_create IS NULL THEN
        RAISE EXCEPTION 'create requires a create object';
      END IF;
      BEGIN
        IF v_row.entity = 'employer' THEN
          IF NULLIF(btrim(v_create->>'employer_name'), '') IS NULL THEN
            RAISE EXCEPTION 'create requires employer_name';
          END IF;
          INSERT INTO public.employers (employer_name, trading_name, employer_category, is_active)
          VALUES (
            btrim(v_create->>'employer_name'),
            NULLIF(btrim(v_create->>'trading_name'), ''),
            NULLIF(btrim(v_create->>'employer_category'), ''),
            true
          )
          RETURNING employer_id INTO v_target;
        ELSE
          IF NULLIF(btrim(v_create->>'worksite_name'), '') IS NULL
             OR NULLIF(btrim(v_create->>'worksite_type'), '') IS NULL THEN
            RAISE EXCEPTION 'create requires worksite_name and worksite_type';
          END IF;
          INSERT INTO public.worksites (worksite_name, worksite_type, is_offshore, is_active)
          VALUES (
            btrim(v_create->>'worksite_name'),
            btrim(v_create->>'worksite_type'),
            COALESCE(NULLIF(v_create->>'is_offshore', '')::boolean, false),
            true
          )
          RETURNING worksite_id INTO v_target;
        END IF;
      EXCEPTION WHEN unique_violation THEN
        RAISE EXCEPTION '% "%" already exists — search for it instead',
          v_row.entity, btrim(COALESCE(v_create->>'employer_name', v_create->>'worksite_name'));
      END;
    ELSE
      v_target := COALESCE(
        NULLIF(CASE WHEN v_row.entity = 'employer' THEN payload->>'employer_id' ELSE payload->>'worksite_id' END, '')::integer,
        CASE WHEN v_row.entity = 'employer' THEN v_row.resolved_employer_id ELSE v_row.resolved_worksite_id END
      );
      IF v_target IS NULL THEN
        RAISE EXCEPTION '% requires %_id', v_action, v_row.entity;
      END IF;
      -- confirm accepts one of the resolver's proposals (provenance stays
      -- 'fuzzy' with its score); a row found by search is an override.
      IF v_action = 'confirm' AND NOT EXISTS (
        SELECT 1 FROM jsonb_array_elements(v_row.candidate_proposals) p
         WHERE (p->>'id')::integer = v_target)
      THEN
        RAISE EXCEPTION 'target % % is not one of the proposals; use override', v_row.entity, v_target;
      END IF;
    END IF;

    IF v_row.entity = 'employer' THEN
      SELECT e.employer_name, e.trading_name INTO v_target_name, v_target_alt
        FROM public.employers e WHERE e.employer_id = v_target;
    ELSE
      SELECT w.worksite_name, NULL INTO v_target_name, v_target_alt
        FROM public.worksites w WHERE w.worksite_id = v_target;
    END IF;
    IF v_target_name IS NULL THEN
      RAISE EXCEPTION '% % not found', v_row.entity, v_target;
    END IF;

    -- 3. Ambiguity guard (the DA1.4 alias lock, applied per decision until
    --    the unique index lands): the same folded string must not already be
    --    an alias of a different row of the same entity.
    IF v_row.entity = 'employer' THEN
      SELECT e.employer_name INTO v_other_name
        FROM public.employer_name_aliases a
        JOIN public.employers e ON e.employer_id = a.employer_id
       WHERE public.fold_name(a.alias_name::text) = v_row.normalised_name
         AND a.employer_id <> v_target
       LIMIT 1;
    ELSE
      SELECT w.worksite_name INTO v_other_name
        FROM public.worksite_name_aliases a
        JOIN public.worksites w ON w.worksite_id = a.worksite_id
       WHERE public.fold_name(a.alias_name::text) = v_row.normalised_name
         AND a.worksite_id <> v_target
       LIMIT 1;
    END IF;
    IF v_other_name IS NOT NULL THEN
      RAISE EXCEPTION 'alias "%" already points at %; resolve that alias first',
        btrim(v_row.raw_name), v_other_name;
    END IF;

    -- 4. Alias write when the raw string is not the canonical (or trading)
    --    name itself. source = 'import' for every accepted match; the
    --    per-row unique index (lower(btrim(alias_name))) is honoured.
    IF v_row.normalised_name <> public.fold_name(v_target_name)
       AND (v_target_alt IS NULL OR v_row.normalised_name <> public.fold_name(v_target_alt)) THEN
      IF v_row.entity = 'employer' THEN
        INSERT INTO public.employer_name_aliases (employer_id, alias_name, source, created_by)
        SELECT v_target, btrim(v_row.raw_name), 'import', auth.uid()
         WHERE NOT EXISTS (
           SELECT 1 FROM public.employer_name_aliases x
            WHERE x.employer_id = v_target
              AND lower(btrim(x.alias_name)) = lower(btrim(v_row.raw_name)));
      ELSE
        INSERT INTO public.worksite_name_aliases (worksite_id, alias_name, source, created_by)
        SELECT v_target, btrim(v_row.raw_name), 'import', auth.uid()
         WHERE NOT EXISTS (
           SELECT 1 FROM public.worksite_name_aliases x
            WHERE x.worksite_id = v_target
              AND lower(btrim(x.alias_name)) = lower(btrim(v_row.raw_name)));
      END IF;
      GET DIAGNOSTICS v_n = ROW_COUNT;
      v_alias_written := v_n > 0;
    END IF;

    v_status := CASE WHEN v_action = 'override' THEN 'overridden' ELSE 'confirmed' END;
    v_method := CASE v_action
                  WHEN 'override' THEN 'manual'
                  WHEN 'create'   THEN 'created'
                  ELSE COALESCE(v_row.match_method, 'fuzzy')
                END;

    -- 5. Back-fill: only a NULL FK is filled, only where the folded raw
    --    string matches, and only for workers whose names came from an
    --    import that queued this string. Nothing non-null is overwritten.
    -- 6. Sibling open rows for the same folded string (other imports) are
    --    resolved with the same target.
    -- 7. The decided row.
    IF v_row.entity = 'employer' THEN
      WITH upd AS (
        UPDATE public.workers w
           SET employer_id = v_target, updated_at = now()
         WHERE w.employer_id IS NULL
           AND w.employer_name_raw IS NOT NULL
           AND public.fold_name(w.employer_name_raw) = v_row.normalised_name
           AND w.names_import_id IN (
             SELECT r.import_id FROM public.name_match_reviews r
              WHERE r.entity = v_row.entity AND r.normalised_name = v_row.normalised_name
                AND r.import_id IS NOT NULL)
        RETURNING w.worker_id)
      SELECT COALESCE(array_agg(worker_id ORDER BY worker_id), '{}'::integer[]) INTO v_backfilled FROM upd;

      UPDATE public.name_match_reviews
         SET status = v_status, match_method = v_method,
             match_score = CASE WHEN v_action = 'confirm' THEN match_score ELSE NULL END,
             resolved_employer_id = v_target,
             decided_by = auth.uid(), decided_at = now(),
             notes = 'resolved with review ' || v_id
       WHERE entity = v_row.entity AND normalised_name = v_row.normalised_name
         AND id <> v_id AND status IN ('needs_review', 'unmatched');
      GET DIAGNOSTICS v_siblings = ROW_COUNT;

      UPDATE public.name_match_reviews
         SET status = v_status, match_method = v_method,
             match_score = CASE WHEN v_action = 'confirm' THEN match_score ELSE NULL END,
             resolved_employer_id = v_target,
             decided_by = auth.uid(), decided_at = now(), notes = v_notes
       WHERE id = v_id
       RETURNING * INTO v_row;
    ELSE
      WITH upd AS (
        UPDATE public.workers w
           SET worksite_id = v_target, updated_at = now()
         WHERE w.worksite_id IS NULL
           AND w.worksite_name_raw IS NOT NULL
           AND public.fold_name(w.worksite_name_raw) = v_row.normalised_name
           AND w.names_import_id IN (
             SELECT r.import_id FROM public.name_match_reviews r
              WHERE r.entity = v_row.entity AND r.normalised_name = v_row.normalised_name
                AND r.import_id IS NOT NULL)
        RETURNING w.worker_id)
      SELECT COALESCE(array_agg(worker_id ORDER BY worker_id), '{}'::integer[]) INTO v_backfilled FROM upd;

      UPDATE public.name_match_reviews
         SET status = v_status, match_method = v_method,
             match_score = CASE WHEN v_action = 'confirm' THEN match_score ELSE NULL END,
             resolved_worksite_id = v_target,
             decided_by = auth.uid(), decided_at = now(),
             notes = 'resolved with review ' || v_id
       WHERE entity = v_row.entity AND normalised_name = v_row.normalised_name
         AND id <> v_id AND status IN ('needs_review', 'unmatched');
      GET DIAGNOSTICS v_siblings = ROW_COUNT;

      UPDATE public.name_match_reviews
         SET status = v_status, match_method = v_method,
             match_score = CASE WHEN v_action = 'confirm' THEN match_score ELSE NULL END,
             resolved_worksite_id = v_target,
             decided_by = auth.uid(), decided_at = now(), notes = v_notes
       WHERE id = v_id
       RETURNING * INTO v_row;
    END IF;

  ELSIF v_action = 'reject' THEN
    IF v_row.status NOT IN ('needs_review', 'unmatched', 'auto') THEN
      RAISE EXCEPTION 'review % is already %; reopen it first', v_id, v_row.status;
    END IF;
    -- Sticky: the resolver returns `rejected` for this folded string on later
    -- imports and does not re-queue it. No alias, no back-fill.
    UPDATE public.name_match_reviews
       SET status = 'rejected', match_method = NULL, match_score = NULL,
           resolved_employer_id = NULL, resolved_worksite_id = NULL,
           decided_by = auth.uid(), decided_at = now(),
           notes = 'resolved with review ' || v_id
     WHERE entity = v_row.entity AND normalised_name = v_row.normalised_name
       AND id <> v_id AND status IN ('needs_review', 'unmatched');
    GET DIAGNOSTICS v_siblings = ROW_COUNT;

    UPDATE public.name_match_reviews
       SET status = 'rejected', match_method = NULL, match_score = NULL,
           resolved_employer_id = NULL, resolved_worksite_id = NULL,
           decided_by = auth.uid(), decided_at = now(), notes = v_notes
     WHERE id = v_id
     RETURNING * INTO v_row;

  ELSIF v_action = 'reopen' THEN
    IF v_row.status NOT IN ('confirmed', 'overridden', 'rejected') THEN
      RAISE EXCEPTION 'review % is %; only a decided review can be reopened', v_id, v_row.status;
    END IF;
    -- The alias and the back-fill are not reverted (plan §2.3.4; an admin
    -- removes a wrong alias with the existing delete policy).
    UPDATE public.name_match_reviews
       SET status = CASE WHEN candidate_proposals = '[]'::jsonb THEN 'unmatched' ELSE 'needs_review' END,
           match_method = CASE WHEN match_method IN ('manual', 'created') THEN NULL ELSE match_method END,
           resolved_employer_id = NULL, resolved_worksite_id = NULL,
           decided_by = NULL, decided_at = NULL,
           notes = COALESCE(v_notes, notes)
     WHERE id = v_id
     RETURNING * INTO v_row;
  END IF;

  RETURN jsonb_build_object(
    'review', to_jsonb(v_row),
