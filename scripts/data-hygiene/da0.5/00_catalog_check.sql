-- ##########################################  BLOCK K  ################################################
-- RECONCILIATION 1 (plan §4): every vessel against the employer register. Organisation names only.
-- link_state:
--   'unlinked'          owner_operator_id IS NULL
--   'exact'             the linked employer's name equals owner_name (case-insensitive)
--   'name_mismatch'     linked, but the employer's name is not the owner name -- adjudicate
--   'dangling'          owner_operator_id set but no employers row (impossible under the FK)
--   'synthetic_787_794' linked into the DA0.2 synthetic set -- must be cleared before DA0.2 runs
SELECT v.vessel_id,
       v.name           AS vessel_name,
       v.owner_name,
       v.relevance,
       v.is_active,
       v.owner_operator_id,
       e.employer_name  AS linked_employer_name,
       e.is_active      AS linked_employer_active,
       CASE
         WHEN v.owner_operator_id IS NULL                       THEN 'unlinked'
         WHEN e.employer_id IS NULL                             THEN 'dangling'
         WHEN v.owner_operator_id BETWEEN 787 AND 794           THEN 'synthetic_787_794'
         WHEN lower(e.employer_name) = lower(v.owner_name)      THEN 'exact'
         ELSE 'name_mismatch'
       END              AS link_state
FROM public.vessels v
LEFT JOIN public.employers e ON e.employer_id = v.owner_operator_id
ORDER BY v.vessel_id;
-- ########################################  END OF BLOCK K  ###########################################

-- ##########################################  BLOCK L  ################################################
-- RECONCILIATION 2 (plan §4): every watch contractor against the employer register.
SELECT w.watch_id,
       w.canonical_name,
       w.aliases,
       w.tier,
       w.is_active,
       w.employer_id,
       e.employer_name  AS linked_employer_name,
       e.is_active      AS linked_employer_active,
       CASE
         WHEN w.employer_id IS NULL                              THEN 'unlinked'
         WHEN e.employer_id IS NULL                              THEN 'dangling'
         WHEN w.employer_id BETWEEN 787 AND 794                  THEN 'synthetic_787_794'
         WHEN lower(e.employer_name) = lower(w.canonical_name)   THEN 'exact'
         ELSE 'name_mismatch'
       END              AS link_state
FROM public.mobilisation_watch_contractors w
LEFT JOIN public.employers e ON e.employer_id = w.employer_id
ORDER BY w.watch_id;
-- ########################################  END OF BLOCK L  ###########################################

-- ##########################################  BLOCK M  ################################################
-- RECONCILIATION 3 (plan §4): every alias string in mobilisation_watch_contractors.aliases against
-- employer_name_aliases and employers. in_employer_name_aliases = 0 means the fourth alias store
-- (plan §1.11) disagrees with the register; DA1.4 folds these in.
WITH alias_rows AS (
  SELECT w.watch_id, w.canonical_name, unnest(w.aliases) AS alias_string
  FROM public.mobilisation_watch_contractors w
)
SELECT a.watch_id,
       a.canonical_name,
       a.alias_string,
       (SELECT count(*) FROM public.employer_name_aliases ena
          WHERE lower(ena.alias_name) = lower(a.alias_string))   AS in_employer_name_aliases,
       (SELECT count(*) FROM public.employers e
          WHERE lower(e.employer_name) = lower(a.alias_string))  AS alias_is_an_employer_name,
       (SELECT count(*) FROM public.employers e
          WHERE lower(e.employer_name) = lower(a.canonical_name)) AS canonical_is_an_employer_name
FROM alias_rows a
ORDER BY a.watch_id, a.alias_string;
-- ########################################  END OF BLOCK M  ###########################################

-- ##########################################  BLOCK N  ################################################
-- RECONCILIATION 4 (plan §4): the summary line for the ledger's incidental findings.
SELECT (SELECT count(*) FROM public.vessels)                                            AS vessels_total,
       (SELECT count(*) FROM public.vessels WHERE owner_operator_id IS NOT NULL)        AS vessels_linked,
       (SELECT count(*) FROM public.vessels v JOIN public.employers e
          ON e.employer_id = v.owner_operator_id
         WHERE lower(e.employer_name) <> lower(v.owner_name))                           AS vessels_name_mismatch,
       (SELECT count(*) FROM public.vessels
         WHERE owner_operator_id BETWEEN 787 AND 794)                                   AS vessels_into_synthetic,
       (SELECT count(*) FROM public.mobilisation_watch_contractors)                     AS contractors_total,
       (SELECT count(*) FROM public.mobilisation_watch_contractors
         WHERE employer_id IS NOT NULL)                                                 AS contractors_linked,
       (SELECT count(*) FROM public.mobilisation_watch_contractors w JOIN public.employers e
          ON e.employer_id = w.employer_id
         WHERE lower(e.employer_name) <> lower(w.canonical_name))                       AS contractors_name_mismatch,
       (SELECT count(*) FROM public.mobilisation_watch_contractors
         WHERE employer_id BETWEEN 787 AND 794)                                         AS contractors_into_synthetic,
       (SELECT count(*) FROM (
          SELECT unnest(aliases) AS a FROM public.mobilisation_watch_contractors
        ) x WHERE NOT EXISTS (
          SELECT 1 FROM public.employer_name_aliases ena WHERE lower(ena.alias_name) = lower(x.a)
        ))                                                                              AS alias_strings_missing_from_register;
-- ########################################  END OF BLOCK N  ###########################################

-- ##########################################  BLOCK O  ################################################
-- Ledger state. This is the precondition 10_record_ledger_row.sql asserts and the post-state it
-- leaves. On production before 10: tables_present = 16, ledger_row_present = f, ledger_max_version
-- = '20260921030000'. On the 12 September clone before the migration: tables_present = 0,
-- ledger_row_present = f, ledger_max_version = '20260917100000'.
SELECT (SELECT count(*) FROM pg_class c
         JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
        WHERE c.relkind = 'r' AND c.relname = ANY (ARRAY[
          'vessels', 'geofences', 'mobilisation_watch_contractors', 'mobilisation_watch_vessels',
          'mobilisation_watch_keywords', 'mobilisation_sources', 'mobilisation_rules',
          'mobilisation_signals', 'mobilisation_alerts', 'mobilisation_alert_signals',
          'mobilisation_alert_events', 'mobilisation_notifications', 'mobilisation_prefs',
          'mobilisation_push_subscriptions', 'mobilisation_positions', 'mobilisation_settings'
        ]))                                                                AS tables_present,
       EXISTS (SELECT 1 FROM supabase_migrations.schema_migrations
                WHERE version = '20260922040000')                          AS ledger_row_present,
       (SELECT max(version) FROM supabase_migrations.schema_migrations)    AS ledger_max_version,
       (SELECT count(*) FROM supabase_migrations.schema_migrations)        AS ledger_rows;
-- ########################################  END OF BLOCK O  ###########################################
