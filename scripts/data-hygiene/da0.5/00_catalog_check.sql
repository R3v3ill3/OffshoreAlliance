-- ########################################  END OF BLOCK E  ###########################################

-- ##########################################  BLOCK F  ################################################
-- Triggers. Expected: 8 rows -- seven BEFORE UPDATE ... update_updated_at() (vessels, geofences,
-- watch_contractors, rules, alerts, prefs, settings) and trg_mobilisation_alert_audit
-- (AFTER UPDATE ON mobilisation_alerts).
SELECT c.relname AS table_name, t.tgname AS trigger_name, pg_get_triggerdef(t.oid) AS definition
FROM pg_trigger t
JOIN pg_class c ON c.oid = t.tgrelid
JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
WHERE NOT t.tgisinternal
  AND c.relname = ANY (ARRAY[
    'vessels', 'geofences', 'mobilisation_watch_contractors', 'mobilisation_watch_vessels',
    'mobilisation_watch_keywords', 'mobilisation_sources', 'mobilisation_rules',
    'mobilisation_signals', 'mobilisation_alerts', 'mobilisation_alert_signals',
    'mobilisation_alert_events', 'mobilisation_notifications', 'mobilisation_prefs',
    'mobilisation_push_subscriptions', 'mobilisation_positions', 'mobilisation_settings'
  ])
ORDER BY c.relname, t.tgname;
-- ########################################  END OF BLOCK F  ###########################################

-- ##########################################  BLOCK G  ################################################
-- Functions. mobilisation_alert_audit is the only one the migration creates; update_updated_at and
-- get_user_role are baseline prerequisites it calls (20260908050000_baseline_schema.sql).
-- Expected md5 of pg_get_functiondef on production, 2026-09-22:
--   mobilisation_alert_audit  764235c6343f9cc8189502ba271571e5
--   update_updated_at         28c4c04688c55a53cda7430cc3b538ed
--   get_user_role             286b2eb565b18a700b6867b6dbcd51f5
SELECT p.proname                          AS function_name,
       pg_get_function_identity_arguments(p.oid) AS args,
       l.lanname                          AS language,
       p.prosecdef                        AS security_definer,
       md5(pg_get_functiondef(p.oid))     AS definition_md5,
       pg_get_functiondef(p.oid)          AS definition
FROM pg_proc p
JOIN pg_namespace n ON n.oid = p.pronamespace AND n.nspname = 'public'
JOIN pg_language l ON l.oid = p.prolang
WHERE p.proname IN ('mobilisation_alert_audit', 'update_updated_at', 'get_user_role')
ORDER BY p.proname;
-- ########################################  END OF BLOCK G  ###########################################

-- ##########################################  BLOCK H  ################################################
-- Table grants for the PostgREST roles. Expected on a Supabase project: anon returns NO rows on any
-- of the sixteen (the migration's REVOKE ALL ... FROM PUBLIC, anon), while authenticated and
-- service_role each show the full privilege set on all sixteen -- because Supabase's default
-- privileges (pg_default_acl, public schema) grant ALL on new tables to anon, authenticated and
-- service_role at CREATE TABLE time, and the migration revokes only from PUBLIC and anon. The
-- migration's explicit per-table GRANT SELECT / INSERT / UPDATE / DELETE lines are therefore a
-- floor, not a ceiling: RLS is what actually gates authenticated. See the plan's §3 note.
SELECT table_name, grantee,
       string_agg(privilege_type, ',' ORDER BY privilege_type) AS privileges
FROM information_schema.role_table_grants
WHERE table_schema = 'public'
  AND grantee IN ('anon', 'authenticated', 'service_role', 'PUBLIC')
  AND table_name = ANY (ARRAY[
    'vessels', 'geofences', 'mobilisation_watch_contractors', 'mobilisation_watch_vessels',
    'mobilisation_watch_keywords', 'mobilisation_sources', 'mobilisation_rules',
    'mobilisation_signals', 'mobilisation_alerts', 'mobilisation_alert_signals',
    'mobilisation_alert_events', 'mobilisation_notifications', 'mobilisation_prefs',
    'mobilisation_push_subscriptions', 'mobilisation_positions', 'mobilisation_settings'
  ])
GROUP BY table_name, grantee
ORDER BY table_name, grantee;
-- ########################################  END OF BLOCK H  ###########################################

-- ##########################################  BLOCK I  ################################################
-- Identity sequences and their privileges. Expected: 12 rows (one per identity column in the
-- migration's final DO block), owner postgres, USAGE true for authenticated and service_role.
SELECT c.relname                                                            AS sequence_name,
       pg_get_userbyid(c.relowner)                                          AS owner,
       has_sequence_privilege('authenticated', 'public.' || c.relname, 'USAGE') AS authenticated_usage,
       has_sequence_privilege('service_role',  'public.' || c.relname, 'USAGE') AS service_role_usage,
       has_sequence_privilege('anon',          'public.' || c.relname, 'USAGE') AS anon_usage
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
WHERE c.relkind = 'S'
  AND c.relname = ANY (ARRAY[
    'vessels_vessel_id_seq', 'geofences_geofence_id_seq',
    'mobilisation_watch_contractors_watch_id_seq',
    'mobilisation_watch_vessels_watch_vessel_id_seq',
    'mobilisation_watch_keywords_keyword_id_seq', 'mobilisation_rules_rule_id_seq',
    'mobilisation_signals_signal_id_seq', 'mobilisation_alerts_alert_id_seq',
    'mobilisation_alert_events_event_id_seq',
    'mobilisation_notifications_notification_id_seq',
    'mobilisation_push_subscriptions_subscription_id_seq',
    'mobilisation_positions_position_id_seq'
  ])
ORDER BY c.relname;
-- ########################################  END OF BLOCK I  ###########################################

