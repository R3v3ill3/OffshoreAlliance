-- ##########################################  BLOCK A  ################################################
-- Table presence, RLS flag and table comment. Expected: 16 rows, rls_enabled = t on all 16,
-- comments on exactly five (vessels, geofences, mobilisation_signals, mobilisation_alert_events,
-- mobilisation_positions).
SELECT c.relname                                   AS table_name,
       c.relrowsecurity                            AS rls_enabled,
       c.relforcerowsecurity                       AS rls_forced,
       obj_description(c.oid, 'pg_class')          AS table_comment
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
WHERE c.relkind = 'r'
  AND c.relname = ANY (ARRAY[
    'vessels', 'geofences', 'mobilisation_watch_contractors', 'mobilisation_watch_vessels',
    'mobilisation_watch_keywords', 'mobilisation_sources', 'mobilisation_rules',
    'mobilisation_signals', 'mobilisation_alerts', 'mobilisation_alert_signals',
    'mobilisation_alert_events', 'mobilisation_notifications', 'mobilisation_prefs',
    'mobilisation_push_subscriptions', 'mobilisation_positions', 'mobilisation_settings'
  ])
ORDER BY c.relname;
-- ########################################  END OF BLOCK A  ###########################################

-- ##########################################  BLOCK B  ################################################
-- Columns: name, ordinal, type, nullability, default, identity. Expected: 171 rows
-- (vessels 23, geofences 9, watch_contractors 10, watch_vessels 5, watch_keywords 6, sources 10,
--  rules 9, signals 26, alerts 21, alert_signals 3, alert_events 8, notifications 9, prefs 7,
--  push_subscriptions 6, positions 11, settings 8). identity = 'd' (GENERATED BY DEFAULT) on the
-- twelve identity keys; '' on mobilisation_sources.source_key, mobilisation_prefs.user_id,
-- mobilisation_settings.id and mobilisation_alert_signals' composite key.
SELECT c.relname                                            AS table_name,
       a.attnum                                             AS ordinal,
       a.attname                                            AS column_name,
       format_type(a.atttypid, a.atttypmod)                 AS data_type,
       a.attnotnull                                         AS not_null,
       pg_get_expr(d.adbin, d.adrelid)                      AS column_default,
       a.attidentity                                        AS identity
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
WHERE c.relname = ANY (ARRAY[
    'vessels', 'geofences', 'mobilisation_watch_contractors', 'mobilisation_watch_vessels',
    'mobilisation_watch_keywords', 'mobilisation_sources', 'mobilisation_rules',
    'mobilisation_signals', 'mobilisation_alerts', 'mobilisation_alert_signals',
    'mobilisation_alert_events', 'mobilisation_notifications', 'mobilisation_prefs',
    'mobilisation_push_subscriptions', 'mobilisation_positions', 'mobilisation_settings'
  ])
ORDER BY c.relname, a.attnum;
-- ########################################  END OF BLOCK B  ###########################################

-- ##########################################  BLOCK C  ################################################
-- Constraints with their full definitions (PRIMARY KEY, UNIQUE, CHECK, FOREIGN KEY incl. ON DELETE).
-- Expected: 72 rows -- 16 primary keys, 13 uniques, 20 checks, 23 foreign keys.
SELECT c.relname                         AS table_name,
       con.conname                       AS constraint_name,
       CASE con.contype WHEN 'p' THEN 'PRIMARY KEY' WHEN 'u' THEN 'UNIQUE'
                        WHEN 'c' THEN 'CHECK'       WHEN 'f' THEN 'FOREIGN KEY'
                        ELSE con.contype::text END AS kind,
       pg_get_constraintdef(con.oid)     AS definition
FROM pg_constraint con
JOIN pg_class c ON c.oid = con.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace AND n.nspname = 'public'
WHERE c.relname = ANY (ARRAY[
    'vessels', 'geofences', 'mobilisation_watch_contractors', 'mobilisation_watch_vessels',
    'mobilisation_watch_keywords', 'mobilisation_sources', 'mobilisation_rules',
    'mobilisation_signals', 'mobilisation_alerts', 'mobilisation_alert_signals',
    'mobilisation_alert_events', 'mobilisation_notifications', 'mobilisation_prefs',
    'mobilisation_push_subscriptions', 'mobilisation_positions', 'mobilisation_settings'
  ])
ORDER BY c.relname, con.contype, con.conname;
-- ########################################  END OF BLOCK C  ###########################################

-- ##########################################  BLOCK D  ################################################
