-- ── Name folding, shared by SQL and TypeScript ──────────────────────────────

-- Byte-for-byte the rule of apps/organising-db/src/lib/import/name-fold.ts:
-- every run of whitespace becomes one space, outer space is trimmed, then
-- lower-cased. Legal suffixes are NOT stripped (exact means exact after
-- folding; suffix tolerance is the fuzzy step's job).
CREATE OR REPLACE FUNCTION "public"."fold_name"("p" "text") RETURNS "text"
    LANGUAGE "sql" IMMUTABLE STRICT PARALLEL SAFE
    AS $$
  SELECT lower(btrim(regexp_replace(p, '\s+', ' ', 'g')));
$$;

ALTER FUNCTION "public"."fold_name"("p" "text") OWNER TO "postgres";

COMMENT ON FUNCTION "public"."fold_name"("p" "text") IS
  'Exact-match key for employer / worksite strings: whitespace collapsed to one space, trimmed, lower-cased. Mirrors lib/import/name-fold.ts.';

